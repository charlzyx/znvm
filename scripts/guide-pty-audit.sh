#!/usr/bin/env bash
# Key-by-key pty transcripts for guide audit (isolated HOME/NVM_DIR).
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
BIN="${ROOT}/zig-out/bin/znvm"
ART="${ARTIFACT_DIR:-/opt/cursor/artifacts}"
DOCS="${ROOT}/docs/guide-pty-transcripts.md"
mkdir -p "$ART" "$(dirname "$DOCS")"
OUT="$ART/guide-pty-transcripts.txt"
: >"$OUT"

if [[ ! -x "$BIN" ]]; then
  (cd "$ROOT" && zig build)
  BIN="${ROOT}/zig-out/bin/znvm"
fi

export NVM_DIR="${NVM_DIR:-/tmp/znvm-pty-audit-$$}"
export HOME="${HOME:-/tmp/znvm-home-audit-$$}"
rm -rf "$NVM_DIR" "$HOME"
mkdir -p "$NVM_DIR/versions/node" "$HOME"
for v in v18.20.4 v20.18.0 v22.11.0; do
  mkdir -p "$NVM_DIR/versions/node/$v/bin"
  printf '#!/bin/sh\necho %s\n' "$v" >"$NVM_DIR/versions/node/$v/bin/node"
  chmod +x "$NVM_DIR/versions/node/$v/bin/node"
done
printf '22.11.0\n' >"$HOME/.nvmrc"
export PATH="/usr/bin:/bin"
export LC_ALL=C LANG=C NVM_LANG=en

python3 - "$BIN" "$NVM_DIR" "$HOME" "$OUT" <<'PY'
import os, pty, select, subprocess, sys, time

bin_path, nvm_dir, home, out_path = sys.argv[1:5]

def run_pty(label, args, env, sends, timeout=8):
    master, slave = pty.openpty()
    proc = subprocess.Popen(
        args, stdin=slave, stdout=slave, stderr=slave, env=env, close_fds=True,
    )
    os.close(slave)
    data = b""
    for item in sends:
        if isinstance(item, tuple) and item[0] == "sleep":
            time.sleep(item[1])
            continue
        raw = item if isinstance(item, (bytes, bytearray)) else item.encode("latin-1")
        os.write(master, raw)
        time.sleep(0.07)
    end = time.time() + timeout
    while time.time() < end:
        r, _, _ = select.select([master], [], [], 0.12)
        if master in r:
            try:
                chunk = os.read(master, 8192)
            except OSError:
                break
            if not chunk:
                break
            data += chunk
        if proc.poll() is not None and not select.select([master], [], [], 0)[0]:
            break
    try:
        os.write(master, b"q")
    except OSError:
        pass
    time.sleep(0.25)
    if proc.poll() is None:
        proc.terminate()
        try:
            proc.wait(timeout=2)
        except subprocess.TimeoutExpired:
            proc.kill()
    try:
        os.close(master)
    except OSError:
        pass
    text = data.decode("utf-8", "replace")
    with open(out_path, "a", encoding="utf-8") as fh:
        fh.write(f"\n=== {label} ===\n")
        fh.write("keys: " + repr(sends) + "\n")
        fh.write(text)
        fh.write("\n")
    print(label, "ok", len(text))

base = {
    "LC_ALL": "C", "LANG": "C", "NVM_LANG": "en",
    "HOME": home, "PATH": "/usr/bin:/bin", "NVM_DIR": nvm_dir,
}

# Bare binary: switch picker (menu 1 -> item 1)
run_pty("bare_switch_installed", [bin_path], base, ["1\r", "1\r", "\r", "0\r"])

# Esc cancel on text input (Switch -> Enter version -> Esc)
run_pty("bare_esc_text_cancel", [bin_path], base, ["1\r", "3\r", "\x1b"])

# Error stays in menu (bad version in use prompt)
run_pty("bare_error_stays", [bin_path], base, ["1\r", "3\r", "99.99.99\r", "0\r"])

# Uninstall y/N default No (Enter declines)
run_pty("bare_uninstall_no", [bin_path], base, ["4\r", "2\r", "\r", "n\r"])

# nrm switch / del (via binary nrm if linked)
nrm = bin_path.replace("znvm", "nrm") if os.path.basename(bin_path) == "znvm" else bin_path
if not os.path.isfile(nrm):
    nrm = bin_path
run_pty("nrm_switch", [nrm], {**base, "NVM_DIR": nvm_dir}, ["1\r", "\r", "0\r"])

shell_env = subprocess.check_output([bin_path, "env"], text=True, env=base)
shell_launch = (
    shell_env
    + f'export NVM_DIR="{nvm_dir}"; export HOME="{home}"; '
    + "stty sane 2>/dev/null; exec bash -i"
)
run_pty(
    "shell_eval_nvm_guide",
    ["bash", "-lc", shell_launch],
    base,
    ["nvm\r", "1\r", "1\r", "\r", "0\r", "0\r"],
    timeout=18,
)
run_pty(
    "bare_binary_guide",
    [bin_path],
    base,
    ["0\r"],
    timeout=4,
)
PY

{
  echo "# Guide pty transcripts (generated by scripts/guide-pty-audit.sh)"
  echo ""
  echo 'Isolated `HOME` and `NVM_DIR` with fake installed v18/v20/v22.'
  echo ""
  cat "$OUT"
} >"$DOCS"

echo "Wrote $OUT and $DOCS"
